-- 1. إنشاء جدول تكاليف C++
CREATE TABLE IF NOT EXISTS public.cpp_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    student_name TEXT NOT NULL,
    student_id TEXT NOT NULL,
    group_name TEXT NOT NULL,
    assignment_name TEXT NOT NULL,
    file_name TEXT NOT NULL,
    file_url TEXT NOT NULL
);

-- 2. إنشاء فهارس لتحسين سرعة البحث والفلترة
CREATE INDEX IF NOT EXISTS idx_cpp_assignments_group ON public.cpp_assignments (group_name);
CREATE INDEX IF NOT EXISTS idx_cpp_assignments_assignment ON public.cpp_assignments (assignment_name);
CREATE INDEX IF NOT EXISTS idx_cpp_assignments_student_id ON public.cpp_assignments (student_id);
CREATE INDEX IF NOT EXISTS idx_cpp_assignments_created_at ON public.cpp_assignments (created_at DESC);

-- 3. تفعيل نظام حماية الصفوف (Row Level Security)
ALTER TABLE public.cpp_assignments ENABLE ROW LEVEL SECURITY;

-- 4. سياسة السماح للطلاب برفع وحفظ تكاليفهم (Insert)
CREATE POLICY "Allow public insert to cpp_assignments" 
ON public.cpp_assignments 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 5. سياسة السماح بعرض التكاليف في لوحة التحكم (Select)
CREATE POLICY "Allow public select on cpp_assignments" 
ON public.cpp_assignments 
FOR SELECT 
TO anon, authenticated 
USING (true);
